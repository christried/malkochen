// "1 dish", "4 dishes".
function dishCount(count: number): string {
  return `${number(count)} ${plural(count, { one: 'dish', other: 'dishes' })}`
}

// "Ada", "Ada and Linus", "Ada, Linus and Grace".
function nameList(names: string[]): string {
  return names.length < 2 ? names.join('') : `${names.slice(0, -1).join(', ')} and ${names.at(-1)}`
}

// Like nameList, but at most three names: "Ada, Linus and Grace", then
// "Ada, Linus and 2 others".
function someNames(names: string[]): string {
  return names.length <= 3 ? nameList(names) : `${names.slice(0, 2).join(', ')} and ${number(names.length - 2)} others`
}

// "1 new dish", "3 new dishes".
function newDishCount(count: number): string {
  return `${number(count)} new ${plural(count, { one: 'dish', other: 'dishes' })}`
}

function commentCount(count: number): string {
  return `${number(count)} ${plural(count, { one: 'comment', other: 'comments' })}`
}

function voteCount(count: number): string {
  return `${number(count)} ${plural(count, { one: 'thumb', other: 'thumbs' })}`
}

function talkCounts(comments: number, votes: number): string[] {
  return [...comments ? [commentCount(comments)] : [], ...votes ? [voteCount(votes)] : []]
}

