// A day by its name, and after the current week with its date: "sabato",
// "giovedì 26 novembre".
function dayNamed(day: string, today: string): string {
  const name = weekday(day).toLowerCase()
  return weekStart(day) === weekStart(today) ? name : `${name} ${dayMonth(day)}`
}

// A day inside a sentence on the Week Plan: "oggi", "domani", then dayNamed.
function dayPhrase(day: string, today: string): string {
  if (day === today) return 'oggi'
  if (day === addDays(today, 1)) return 'domani'
  return dayNamed(day, today)
}

// "1 piatto", "4 piatti".
function dishCount(count: number): string {
  return `${number(count)} ${plural(count, { one: 'piatto', other: 'piatti' })}`
}

// A participle after a count of Dishes: "1 piatto trovato", "3 piatti
// trovati". `stem` without its ending ("trovat").
function dishesDone(count: number, stem: string): string {
  return `${dishCount(count)} ${stem}${plural(count, { one: 'o', other: 'i' })}`
}

// "Ada", "Ada e Linus", "Ada, Linus e Grace".
function nameList(names: string[]): string {
  return names.length < 2 ? names.join('') : `${names.slice(0, -1).join(', ')} e ${names.at(-1)}`
}

// Like nameList, but at most three names: "Ada, Linus e Grace", then
// "Ada, Linus e altri 2".
function someNames(names: string[]): string {
  return names.length <= 3 ? nameList(names) : `${names.slice(0, 2).join(', ')} e altri ${number(names.length - 2)}`
}

// "1 nuovo piatto", "3 nuovi piatti".
function newDishCount(count: number): string {
  return `${number(count)} ${plural(count, { one: 'nuovo piatto', other: 'nuovi piatti' })}`
}

function commentCount(count: number): string {
  return `${number(count)} ${plural(count, { one: 'commento', other: 'commenti' })}`
}

function voteCount(count: number): string {
  return `${number(count)} ${plural(count, { one: 'pollice', other: 'pollici' })}`
}

function talkCounts(comments: number, votes: number): string[] {
  return [...comments ? [commentCount(comments)] : [], ...votes ? [voteCount(votes)] : []]
}

